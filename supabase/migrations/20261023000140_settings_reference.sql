-- 0140 · settings and reference data (docs/02 settings keys, docs/06, docs/13 "Reference seed")
-- Reference data lives in a migration (not seed.sql) so every environment, including production, gets it.
-- Values marked TODO(MCCI) in docs/14 are defaults until MCCI decides; they are edited later through Settings.
-- Finding F-16: settings were readable by anonymous users; now private with a whitelisted public view.

create table private.settings (
  key text primary key,
  value jsonb not null,
  updated_by uuid references public.profiles,
  updated_at timestamptz not null default now()
);

create table public.document_requirements (      -- docs/05 M3: proprietorship 7 slots, Pvt Ltd 11
  biz_type public.biz_type not null,
  key text not null,
  label_en text not null,
  label_ur text,                                 -- Urdu labels are not in the specs yet (gap, docs/17 §12)
  short_en text,
  required boolean not null default true,
  sort smallint not null,
  primary key (biz_type, key)
);

create table public.service_types (              -- the seven services (reference-data.json "SV")
  key text primary key,
  name_en text not null,
  full_name_en text,
  name_ur text,
  fee int not null default 0 check (fee >= 0),   -- PKR; placeholders until MCCI confirms (docs/14)
  docs jsonb not null,
  fields jsonb not null,
  sla_hours int not null default 24 check (sla_hours > 0),
  active boolean not null default true,
  sort smallint not null default 0
);

create table public.email_templates (            -- docs/07; wording is authored in M8 (not in the specs, not seeded)
  key text primary key,
  event text not null,
  subject_en text not null, subject_ur text,
  body_en text not null, body_ur text,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

alter table private.settings enable row level security;
alter table public.document_requirements enable row level security;
alter table public.service_types enable row level security;
alter table public.email_templates enable row level security;

grant select on public.document_requirements, public.service_types to anon, authenticated;
create policy doc_reqs_read on public.document_requirements for select to anon, authenticated using (true);
create policy service_types_read on public.service_types for select to anon, authenticated using (active or (select private.staff_level('plat')) >= 1);

grant select on public.email_templates to authenticated;
create policy email_templates_read on public.email_templates for select to authenticated using ((select private.staff_level('eng')) >= 1);

-- Public, non-secret settings only (F-16). Add a key here only after confirming it is safe to publish.
create view public.public_settings with (security_invoker = false) as
  select key, value from private.settings where key in ('chamber', 'fees', 'lang', 'app');
grant select on public.public_settings to anon, authenticated;

-- Server-side reads for trusted handlers (PDF, cron) that cannot reach the private schema over the API.
create function api.settings_for_server() returns jsonb
  language sql stable security definer set search_path = ''
  as $$ select coalesce(jsonb_object_agg(s.key, s.value), '{}'::jsonb) from private.settings s $$;
revoke all on function api.settings_for_server() from public, anon, authenticated;
grant execute on function api.settings_for_server() to service_role;

