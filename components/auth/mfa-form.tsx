'use client';

import { useActionState } from 'react';
import type { Locale } from '@/i18n/routing';
import { verifyTotp, type MfaFormState } from '@/lib/auth/actions';

export interface MfaText {
  title: string;
  help: string;
  secret: string;
  code: string;
  verify: string;
  working: string;
}

/** Staff 2-step login: TOTP enrolment (QR + key) or challenge. The code is verified by Supabase Auth on the server. */
export function MfaForm({
  locale,
  factorId,
  qr,
  secret,
  text,
}: {
  locale: Locale;
  factorId: string;
  qr?: string;
  secret?: string;
  text: MfaText;
}) {
  const [state, action, pending] = useActionState<MfaFormState, FormData>(verifyTotp, {});
  return (
    <form action={action} className="grid gap-[14px]">
      <input type="hidden" name="locale" value={locale} />
      <input type="hidden" name="factorId" value={factorId} />
      <h2 className="text-[22px] font-extrabold tracking-[-0.01em]">{text.title}</h2>
      <p className="text-[14px] text-muted">{text.help}</p>
      {qr && (
        <div className="w-fit rounded-[14px] border border-line bg-white p-3">
          {/* data: URL generated by Supabase Auth for this enrolment only */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src={qr} width={184} height={184} alt="" />
        </div>
      )}
      {secret && (
        <p className="text-[13px] text-muted">
          {text.secret}: <code className="font-mono text-[14px] break-all text-ink">{secret}</code>
        </p>
      )}
      <label className="form-field">
        {text.code}
        <input
          name="code"
          inputMode="numeric"
          autoComplete="one-time-code"
          pattern="\d{6}"
          maxLength={6}
          required
          autoFocus
        />
      </label>
      {state.error && (
        <p
          role="alert"
          className="rounded-[10px] border border-[#f3c7c7] bg-[#fdecec] px-3 py-2 text-[14px] text-[#9b1c1c]"
        >
          {state.error}
        </p>
      )}
      <div>
        <button className="btn btn-primary btn-big" data-action="login.staff" disabled={pending}>
          {pending ? text.working : text.verify}
        </button>
      </div>
    </form>
  );
}
