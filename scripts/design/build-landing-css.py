"""Builds app/styles/landing.css from the owner's website design (docs: scripts/design/scope-web-css.mjs).

  part 1  the design's styles.css scoped under .lp, plus the app's hand adjustments below (each must still apply)
  part 2  everything after the first app-additions marker in the current landing.css (real data, the Android app,
          sign-in/sign-up = the unchanged auth.css, the real forms, header widths), kept as it is

Usage: python scripts/design/build-landing-css.py "<Website front MCCI>/assets/css/styles.css"
"""
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / 'app/styles/landing.css'
MARKER = '/* ================= HERO LIVE STATS: real figures'

HEADER = '''/*
 * The owner's website design ("Website front MCCI", 6 Nov 2026; earlier "Login Page Design"): the public website
 * (home and inner pages) and the sign-in / sign-up pages. Generated by scripts/design/build-landing-css.py from its
 * styles.css (part 1, every rule scoped under .lp with display:contents so it never leaks into the rest of the app,
 * keyframes prefixed lp-, the self-hosted faces) followed by the app's own additions (part 2): real data, real
 * forms, the Android app, tap targets, and the unchanged auth.css. The design is light in both themes.
 */
'''

# (old, new): the app's adjustments to the design, carried from the first port; every one must match once
FIXES = [
    # shared app tokens fixed to the light design, and .lp itself takes no box
    ('--shadow:0 18px 44px -22px rgba(6,18,13,.35);',
     '--shadow:0 18px 44px -22px rgba(6,18,13,.35);\n  --line-strong:#7f9186; /* form borders: 3:1 against white and paper (WCAG 1.4.11) */\n'
     '  /* the app\'s shared tokens, fixed to the light design so forms and notices inside these pages match it in dark mode too */\n'
     '  --bg:#fff;--bg2:#fff;--card:#fff;--card2:#f3f6f2;--b:rgba(13,26,20,.16);--t:#0d1a14;--m:#55665d;--hov:#e7ede7;--gt:#00663b;--em:#007845;--em-2:#005c35;--brand:#007845;--input-b:#7f9186;--input-bg:#fff;\n'
     '  color-scheme:light;\n  display:contents;'),
    # html / body base rules: the app shell owns scrolling and the page background
    ('.lp{-webkit-text-size-adjust:100%;scroll-padding-top:calc(var(--hdr-h) + 72px);scroll-behavior:smooth}\n', ''),
    ('.lp{margin:0;background:var(--paper);color:var(--tx);font:500 16px/1.65 var(--sans);overflow-x:hidden;-webkit-font-smoothing:antialiased}',
     '.lp{color:var(--tx);font:500 16px/1.65 var(--sans);-webkit-font-smoothing:antialiased}'),
    # the news ticker sits above the sticky header
    ('.lp .hdr{position:sticky;top:env(safe-area-inset-top,0px);',
     '.lp .hdr{position:sticky;top:calc(env(safe-area-inset-top,0px) + var(--tk,0px));'),
    ('inset:calc(var(--hdr-h) + env(safe-area-inset-top,0px)) 0 0;', 'inset:calc(var(--hdr-h) + var(--tk,0px) + env(safe-area-inset-top,0px)) 0 0;'),
    ('--mx:90%;', '--mx:var(--lp-mx,90%);'),
    # Urdu sizing on the root, the body rule on .lp
    ('html[lang="ur"] .lp{font-size:120%}', 'html[lang="ur"]:has(.lp){font-size:120%}'),
    ('html[lang="ur"] .lp body{', 'html[lang="ur"] .lp{'),
    # contrast: form borders and the dark verify box
    ('border:1px solid var(--line);background:var(--paper);color:var(--tx);font:600 .95rem var(--sans);resize:vertical;',
     'border:1px solid var(--line-strong);background:var(--paper);color:var(--tx);font:600 .95rem var(--sans);resize:vertical;'),
    ('.lp .verify input::placeholder{color:rgba(163,184,173,.6)}', '.lp .verify input::placeholder{color:#a3b8ad}'),
]
OPTIONAL = {
    '.lp .skip{', '.lp .skip:focus{',  # the app has its own skip link
}


def main() -> None:
    css = subprocess.run(['node', str(ROOT / 'scripts/design/scope-web-css.mjs'), sys.argv[1]],
                         check=True, capture_output=True, text=True, encoding='utf-8').stdout
    missing = []
    for old, new in FIXES:
        if css.count(old) != 1:
            missing.append(old[:70])
            continue
        css = css.replace(old, new)
    # drop the design's own skip link and the global reduced-motion kill (the app handles both)
    css = '\n'.join(l for l in css.split('\n') if not any(l.startswith(o) for o in OPTIONAL))
    css = css.replace('  .lp{scroll-behavior:auto}\n', '')
    css = css.replace('  .lp *,.lp *::before,.lp *::after{animation-duration:.01ms!important;animation-iteration-count:1!important;transition-duration:.01ms!important}\n', '')
    current = TARGET.read_text(encoding='utf-8')
    tail = current[current.index(MARKER):]
    TARGET.write_text(HEADER + css.rstrip() + '\n\n' + tail, encoding='utf-8', newline='\n')
    if missing:
        print('fixes that no longer match (check by hand):')
        for m in missing:
            print('  -', m)
    print(f'wrote {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
